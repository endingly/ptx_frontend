def generate_resolved_checker_descriptor_source(
    database: CodegenDatabase,
    *,
    output_path: Path,
) -> None:
    """Generate private checker descriptor storage and instruction getters."""

    instructions = tuple(
        from_instruction_spec(instruction) for instruction in database.instructions
    )
    _validate_unique_cpp_names(instructions)
    storage_definitions = "\n\n".join(
        _emit_instruction_descriptor_storage(instruction) for instruction in instructions
    )
    getter_definitions = "\n\n".join(
        _emit_instruction_descriptor_getter(instruction) for instruction in instructions
    )
    content = f"""// Generated by python/scripts/gen_all.py. Do not edit.
{generated_at_comment()}

#include <ptx_frontend/resolved_ir/ptx_resolved_ir_checker.hpp>
#include <ptx_frontend/resolved_ir/ptx_resolved_ir.hpp>

namespace ptx_frontend::resolved_ir {{

namespace generated_detail {{

{storage_definitions}

}}  // namespace generated_detail

{getter_definitions}

}}  // namespace ptx_frontend::resolved_ir
"""

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")


def _emit_instruction_descriptor_storage(instruction: ResolvedInstruction) -> str:
    storage_name = f"{instruction.cpp_name}CheckerDescriptorStorage"
    modifier_value_definitions = "\n\n".join(
        _emit_variant_modifier_value_descriptors(variant)
        for variant in instruction.variants
    )
    layout_definitions = "\n\n".join(
        _emit_variant_layout_descriptors(variant)
        for variant in instruction.variants
    )
    type_compatibility_definitions = "\n\n".join(
        _emit_variant_type_compatibility_descriptors(variant)
        for variant in instruction.variants
    )
    immediate_value_definitions = "\n\n".join(
        _emit_variant_immediate_value_descriptors(variant)
        for variant in instruction.variants
        if variant.immediate_value is not None
    )
    immediate_range_definitions = "\n\n".join(
        _emit_variant_immediate_range_descriptors(variant)
        for variant in instruction.variants
        if variant.immediate_ranges
    )
    address_alignment_definitions = "\n\n".join(
        _emit_variant_address_alignment_descriptors(variant)
        for variant in instruction.variants
        if variant.address_alignment is not None
    )
    variants = ",\n".join(
        _emit_variant_descriptor(variant) for variant in instruction.variants
    )
    return f"""struct {storage_name} {{
{modifier_value_definitions}

{layout_definitions}

{type_compatibility_definitions}

{immediate_value_definitions}

{immediate_range_definitions}

{address_alignment_definitions}

  static constexpr std::array<checker::VariantDescriptor, {len(instruction.variants)}>
      variants = {{
{variants}
      }};

  static constexpr checker::InstructionDescriptor descriptor{{
      .opcode_name = "{instruction.opcode}",
      .variants = variants,
  }};
}};
"""



def _emit_instruction_descriptor_getter(instruction: ResolvedInstruction) -> str:
    """Emit the checker descriptor getter outside generated_detail."""

    storage_name = f"{instruction.cpp_name}CheckerDescriptorStorage"
    return f"""\
const checker::InstructionDescriptor&
{instruction.cpp_name}::get_checker_descriptor() noexcept {{
  return generated_detail::{storage_name}::descriptor;
}}"""


def _emit_variant_descriptor(variant: ResolvedVariant) -> str:
    rule_id = variant.rule or ""
    consistency = variant.memory_consistency
    alignment = variant.address_alignment
    memory_consistency = ""
    if consistency is not None:
        memory_consistency = f'''
              .memory_consistency = {{
                  .semantics_field_id = "{consistency.semantics_field_id}",
                  .scope_field_id = "{consistency.scope_field_id}",
                  .mmio_field_id = "{consistency.mmio_field_id}",
                  .cache_field_id = "{consistency.cache_field_id}",
                  .address_field_id = "{consistency.address_field_id}",
                  .state_space_field_id = "{consistency.state_space_field_id or ""}",
              }},'''
    vector = variant.memory_vector
    memory_vector = ""
    if vector is not None:
        memory_vector = f'''
              .memory_vector = {{
                  .type_field_id = "{vector.type_field_id}",
                  .vector_field_id = "{vector.vector_field_id}",
                  .address_field_id = "{vector.address_field_id}",
                  .state_space_field_id = "{vector.state_space_field_id or ""}",
                  .availability = {_emit_availability(dict(vector.availability))},
              }},'''
    immediate_value = ""
    if variant.immediate_value is not None:
        immediate_value = f'''
              .immediate_value = {{
                  .operand_field_id = "{variant.immediate_value.operand_field_id}",
                  .allowed_values = {variant.cpp_name}_immediate_value_values,
              }},'''
    immediate_ranges = ""
    if variant.immediate_ranges:
        immediate_ranges = f'''
              .immediate_ranges = {variant.cpp_name}_immediate_ranges,'''
    immediate_multiple_of = ""
    if variant.immediate_multiple_of is not None:
        immediate_multiple_of = f'''
              .immediate_multiple_of = {{
                  .operand_field_id = "{variant.immediate_multiple_of.operand_field_id}",
                  .divisor = {_cpp_uint64(variant.immediate_multiple_of.divisor)},
              }},'''
    return f"""          checker::VariantDescriptor{{
              .variant_name = "{variant.cpp_name}",
              .availability = {_emit_availability(dict(variant.availability))},
              .modifier_value_availabilities =
                  {variant.cpp_name}_modifier_value_availabilities,
              .operand_layouts = {variant.cpp_name}_operand_layouts,
              .operand_type_compatibilities =
                  {variant.cpp_name}_operand_type_compatibilities,
              .rule_id = "{rule_id}",
{memory_consistency}
{_emit_address_alignment_descriptor(variant)}
{memory_vector}
{immediate_value}
{immediate_multiple_of}
{immediate_ranges}
          }}"""


def _emit_variant_immediate_value_descriptors(variant: ResolvedVariant) -> str:
    constraint = variant.immediate_value
    assert constraint is not None
    values = ", ".join(_cpp_uint64(value) for value in constraint.values)
    return f"""  static constexpr std::array<uint64_t, {len(constraint.values)}>
      {variant.cpp_name}_immediate_value_values = {{{{{values}}}}};"""


def _emit_variant_immediate_range_descriptors(variant: ResolvedVariant) -> str:
    entries = ",\n".join(
        f'''          checker::VariantDescriptor::ImmediateRangeDescriptor{{
              .operand_field_id = "{constraint.operand_field_id}",
              .minimum = {_cpp_uint64(constraint.minimum)},
              .has_maximum = {str(constraint.maximum is not None).lower()},
              .maximum = {_cpp_uint64(constraint.maximum) if constraint.maximum is not None else "~uint64_t{0}"},
          }}'''
        for constraint in variant.immediate_ranges
    )
    return f"""  static constexpr std::array<checker::VariantDescriptor::ImmediateRangeDescriptor, {len(variant.immediate_ranges)}>
      {variant.cpp_name}_immediate_ranges = {{{{
{entries}
      }}}};"""


def _cpp_uint64(value: int) -> str:
    """Emit one portable exact uint64_t initializer from normalized metadata."""

    return f"uint64_t{{{value}ULL}}"


def _emit_address_alignment_descriptor(variant: ResolvedVariant) -> str:
    alignment = variant.address_alignment
    if alignment is None:
        return ""
    return f'''              .address_alignment = {{
                  .address_field_ids = {variant.cpp_name}_address_alignment_address_fields,
                  .type_field_id = "{alignment.type_field_id or ""}",
                  .vector_field_id = "{alignment.vector_field_id or ""}",
                  .immediate_operand_field_id = "{alignment.immediate_operand_field_id or ""}",
                  .alignment = {alignment.alignment or 0},
              }},'''


def _emit_variant_address_alignment_descriptors(variant: ResolvedVariant) -> str:
    alignment = variant.address_alignment
    assert alignment is not None
    addresses = ", ".join(f'"{address}"' for address in alignment.address_field_ids)
    return f"""  static constexpr std::array<std::string_view, {len(alignment.address_field_ids)}>
      {variant.cpp_name}_address_alignment_address_fields = {{{{{addresses}}}}};"""


def _emit_variant_modifier_value_descriptors(variant: ResolvedVariant) -> str:
    entries = ",\n".join(
        _emit_modifier_value_descriptor(entry)
        for entry in variant.modifier_value_availabilities
    )
    return f"""  static constexpr std::array<checker::ModifierValueAvailabilityDescriptor, {len(variant.modifier_value_availabilities)}>
      {variant.cpp_name}_modifier_value_availabilities = {{
{entries}
      }};"""


