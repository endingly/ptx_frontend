def generate_resolved_descriptor_source(
    database: CodegenDatabase,
    *,
    output_path: Path,
) -> None:
    """Generate one private C++ source for resolved descriptor storage."""

    instructions = tuple(
        from_instruction_spec(instruction) for instruction in database.instructions
    )
    _validate_unique_cpp_names(instructions)
    storage_definitions = "\n\n".join(
        _emit_resolved_descriptor_storage(instruction)
        for instruction in instructions
    )
    getter_definitions = "\n\n".join(
        _emit_resolved_descriptor_getter(instruction)
        for instruction in instructions
    )
    content = f"""// Generated by python/scripts/gen_all.py. Do not edit.
{generated_at_comment()}

#include <ptx_frontend/resolved_ir/ptx_resolved_ir.hpp>

namespace ptx_frontend::resolved_ir {{

namespace generated_detail {{

{storage_definitions}

}}  // namespace generated_detail

{getter_definitions}

}}  // namespace ptx_frontend::resolved_ir
"""

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")


def _emit_resolved_instruction_implementation(
    instruction: ResolvedInstruction,
) -> str:
    return (
        f"{_emit_resolved_descriptor_storage(instruction)}\n\n"
        f"{_emit_resolved_descriptor_getter(instruction)}"
    )


def _emit_resolved_descriptor_storage(
    instruction: ResolvedInstruction,
) -> str:
    storage_name = f"{instruction.cpp_name}ResolvedDescriptorStorage"
    variant_storage = "\n\n".join(
        _emit_resolved_variant_storage(variant) for variant in instruction.variants
    )
    variants = ",\n".join(
        _emit_resolved_variant_descriptor(variant) for variant in instruction.variants
    )

    return f"""struct {storage_name} {{
{variant_storage}

  static constexpr std::array<check_end::ResolvedVariantDescriptor, {len(instruction.variants)}>
      variants = {{
{variants}
      }};

  static constexpr check_end::ResolvedInstructionDescriptor descriptor{{
      .opcode_name = "{instruction.opcode}",
      .variants = variants,
  }};
}};
"""



def _emit_resolved_descriptor_getter(
    instruction: ResolvedInstruction,
) -> str:
    """Emit the resolved descriptor getter outside generated_detail."""

    storage_name = f"{instruction.cpp_name}ResolvedDescriptorStorage"
    return f"""\
const check_end::ResolvedInstructionDescriptor&
{instruction.cpp_name}::get_resolved_descriptor() noexcept {{
  return generated_detail::{storage_name}::descriptor;
}}"""


def _emit_resolved_variant_storage(variant: ResolvedVariant) -> str:
    name = to_file_stem(variant.variant_id)
    fields = ",\n".join(
        _emit_resolved_field_descriptor(field) for field in variant.modifier_fields
    )
    modifier_bindings = ",\n".join(
        _emit_modifier_binding_descriptor(binding)
        for binding in variant.modifier_bindings
    )
    operand_layout_storage = "\n\n".join(
        _emit_operand_layout_storage(name, index, layout)
        for index, layout in enumerate(variant.operand_layouts)
    )
    operand_layouts = ",\n".join(
        f"""check_end::ResolvedOperandLayoutDescriptor{{
              .layout_id = "{layout.layout_id}",
              .fields = {name}_operand_layout_{index}_fields,
              .bindings = {name}_operand_layout_{index}_bindings,
          }}"""
        for index, layout in enumerate(variant.operand_layouts)
    )

    return f"""  static constexpr std::array<check_end::ResolvedFieldDescriptor, {len(variant.modifier_fields)}>
      {name}_fields = {{
{fields}
      }};

  static constexpr std::array<check_end::ResolvedModifierBindingDescriptor, {len(variant.modifier_bindings)}>
      {name}_modifier_bindings = {{
{modifier_bindings}
      }};

{operand_layout_storage}

  static constexpr std::array<check_end::ResolvedOperandLayoutDescriptor, {len(variant.operand_layouts)}>
      {name}_operand_layouts = {{
{operand_layouts}
      }};"""


def _emit_resolved_field_descriptor(field: ResolvedField) -> str:
    return f"""          check_end::ResolvedFieldDescriptor{{
              .field_id = "{field.name}",
              .value_kind = {cpp_value(CppDomain.RESOLVED_VALUE_KINDS, field.value_kind.value)},
          }}"""


def _emit_modifier_binding_descriptor(binding: ResolvedModifierBinding) -> str:
    return f"""          check_end::ResolvedModifierBindingDescriptor{{
              .source_kind_id = "{binding.source_kind_id}",
              .target_field_id = "{binding.target_field_id}",
              .default_value = {_emit_modifier_default_descriptor(binding)},
          }}"""


def _emit_modifier_default_descriptor(binding: ResolvedModifierBinding) -> str:
    default = binding.default_value
    if default is None:
        return "check_end::ResolvedModifierDefaultDescriptor{}"
    if default.value_cpp_type == "bool" and type(default.value) is bool:
        bool_value = "true" if default.value else "false"
        return f"""check_end::ResolvedModifierDefaultDescriptor{{
                  .kind = {cpp_value(CppDomain.RESOLVED_MODIFIER_DEFAULT_KINDS, "Bool")},
                  .bool_value = {bool_value},
                  .scalar_type = {cpp_default(CppDomain.SCALAR_TYPES)},
                  .rounding_mode = {cpp_default(CppDomain.ROUNDING_MODES)},
                  .cache_operator = {cpp_default(CppDomain.CACHE_OPERATORS)},
              }}"""
    if default.value_cpp_type == "ScalarType" and isinstance(default.value, str):
        scalar_type = cpp_value(CppDomain.SCALAR_TYPES, default.value)
        return f"""check_end::ResolvedModifierDefaultDescriptor{{
                  .kind = {cpp_value(CppDomain.RESOLVED_MODIFIER_DEFAULT_KINDS, "ScalarType")},
                  .bool_value = false,
                  .scalar_type = {scalar_type},
                  .rounding_mode = {cpp_default(CppDomain.ROUNDING_MODES)},
                  .cache_operator = {cpp_default(CppDomain.CACHE_OPERATORS)},
              }}"""
    if default.value_cpp_type == "RoundingMode" and isinstance(
        default.value, str
    ):
        rounding_mode = cpp_value(CppDomain.ROUNDING_MODES, default.value)
        return f"""check_end::ResolvedModifierDefaultDescriptor{{
                  .kind = {cpp_value(CppDomain.RESOLVED_MODIFIER_DEFAULT_KINDS, "RoundingMode")},
                  .bool_value = false,
                  .scalar_type = {cpp_default(CppDomain.SCALAR_TYPES)},
                  .rounding_mode = {rounding_mode},
                  .cache_operator = {cpp_default(CppDomain.CACHE_OPERATORS)},
              }}"""
    if default.value_cpp_type == "CacheOperator" and isinstance(
        default.value, str
    ):
        cache_operator = cpp_value(CppDomain.CACHE_OPERATORS, default.value)
        return f"""check_end::ResolvedModifierDefaultDescriptor{{
                  .kind = {cpp_value(CppDomain.RESOLVED_MODIFIER_DEFAULT_KINDS, "CacheOperator")},
                  .bool_value = false,
                  .scalar_type = {cpp_default(CppDomain.SCALAR_TYPES)},
                  .rounding_mode = {cpp_default(CppDomain.ROUNDING_MODES)},
                  .cache_operator = {cache_operator},
              }}"""
    if default.value_cpp_type == "MemoryStateSpace" and isinstance(
        default.value, str
    ):
        memory_state_space = cpp_value(
            CppDomain.MEMORY_STATE_SPACES, default.value
        )
        return f"""check_end::ResolvedModifierDefaultDescriptor{{
                  .kind = {cpp_value(CppDomain.RESOLVED_MODIFIER_DEFAULT_KINDS, "MemoryStateSpace")},
                  .bool_value = false,
                  .scalar_type = {cpp_default(CppDomain.SCALAR_TYPES)},
                  .rounding_mode = {cpp_default(CppDomain.ROUNDING_MODES)},
                  .cache_operator = {cpp_default(CppDomain.CACHE_OPERATORS)},
                  .memory_state_space = {memory_state_space},
              }}"""
    if default.value_cpp_type == "MemoryConsistency" and isinstance(
        default.value, str
    ):
        value = cpp_value(CppDomain.MEMORY_CONSISTENCIES, default.value)
        return f"""check_end::ResolvedModifierDefaultDescriptor{{
                  .kind = {cpp_value(CppDomain.RESOLVED_MODIFIER_DEFAULT_KINDS, "MemoryConsistency")},
                  .memory_consistency = {value},
              }}"""
    if default.value_cpp_type == "MemoryScope" and isinstance(default.value, str):
        value = cpp_value(CppDomain.MEMORY_SCOPES, default.value)
        return f"""check_end::ResolvedModifierDefaultDescriptor{{
                  .kind = {cpp_value(CppDomain.RESOLVED_MODIFIER_DEFAULT_KINDS, "MemoryScope")},
                  .memory_scope = {value},
              }}"""
    if default.value_cpp_type == "MbarrierPhaseType" and isinstance(default.value, str):
        value = cpp_value(CppDomain.MBARRIER_PHASE_TYPES, default.value)
        return f"""check_end::ResolvedModifierDefaultDescriptor{{
                  .kind = {cpp_value(CppDomain.RESOLVED_MODIFIER_DEFAULT_KINDS, "MbarrierPhaseType")},
                  .mbarrier_phase_type = {value},
              }}"""
    if default.value_cpp_type == "MbarrierLayout" and isinstance(default.value, str):
        value = cpp_value(CppDomain.MBARRIER_LAYOUTS, default.value)
        return f"""check_end::ResolvedModifierDefaultDescriptor{{
                  .kind = {cpp_value(CppDomain.RESOLVED_MODIFIER_DEFAULT_KINDS, "MbarrierLayout")},
                  .mbarrier_layout = {value},
              }}"""
    raise ValueError(
        f"unsupported modifier default {default.value!r} for "
        f"{default.value_cpp_type}"
    )


def _emit_operand_layout_storage(
    variant_name: str,
    layout_index: int,
    layout: ResolvedOperandLayout,
) -> str:
    fields = ",\n".join(
        _emit_resolved_field_descriptor(field) for field in layout.fields
    )
    vector_arities = "\n\n".join(
        f"""  static constexpr std::array<uint8_t, {len(binding.allowed_vector_arities)}>
      {variant_name}_operand_layout_{layout_index}_binding_{binding_index}_vector_arities = {{{{
{_emit_vector_arities(binding.allowed_vector_arities)}
      }}}};"""
        for binding_index, binding in enumerate(layout.bindings)
        if binding.allowed_vector_arities
    )
    address_state_spaces = "\n\n".join(
        f"""  static constexpr std::array<checker::AddressStateSpaceDescriptor, {len(binding.allowed_address_state_spaces)}>
      {variant_name}_operand_layout_{layout_index}_binding_{binding_index}_address_state_spaces = {{{{
{_emit_address_state_spaces(binding.allowed_address_state_spaces)}
      }}}};"""
        for binding_index, binding in enumerate(layout.bindings)
        if binding.allowed_address_state_spaces
    )
    bindings = ",\n".join(
        _emit_operand_binding_descriptor(
            binding,
            f"{variant_name}_operand_layout_{layout_index}_binding_{binding_index}_vector_arities",
            f"{variant_name}_operand_layout_{layout_index}_binding_{binding_index}_address_state_spaces",
        )
        for binding_index, binding in enumerate(layout.bindings)
    )
    return f"""{vector_arities}

{address_state_spaces}

  static constexpr std::array<check_end::ResolvedFieldDescriptor, {len(layout.fields)}>
      {variant_name}_operand_layout_{layout_index}_fields = {{
{fields}
      }};

  static constexpr std::array<check_end::ResolvedOperandBindingDescriptor, {len(layout.bindings)}>
      {variant_name}_operand_layout_{layout_index}_bindings = {{
{bindings}
      }};"""


def _emit_vector_arities(arities: tuple[int, ...]) -> str:
    return ",\n".join(f"          {arity}" for arity in arities)


def _emit_address_state_spaces(entries) -> str:
    result: list[str] = []
    for entry in entries:
        result.append(
            f"""          checker::AddressStateSpaceDescriptor{{
              .state_space = {cpp_value(CppDomain.MEMORY_STATE_SPACES, entry.value)},
              .availability = {_emit_availability(dict(entry.availability))},
          }}"""
        )
    return ",\n".join(result)


def _emit_operand_binding_descriptor(
    binding, vector_arities_name: str, address_state_spaces_name: str
) -> str:
    allowed_shapes = " | ".join(
        cpp_value(CppDomain.RESOLVED_OPERAND_SHAPES, shape.value)
        for shape in binding.allowed_shapes
    )
    vector_arities = (
        f"\n              .allowed_vector_arities = {vector_arities_name},"
        if binding.allowed_vector_arities
        else ""
    )
    vector_arity_modifier = (
        "\n              .vector_arity_modifier_field_id = "
        f'"{binding.vector_arity_modifier_field_id}",'
        if binding.vector_arity_modifier_field_id is not None
        else ""
    )
    vector_policy = (
        "\n              .vector_type_policy = "
        f"checker::VectorTypePolicy::{binding.vector_type_policy.value},"
        if binding.allowed_vector_arities
        or binding.vector_arity_modifier_field_id is not None
        else ""
    )
    allow_vector_sink = (
        "\n              .allow_vector_sink = "
        f'{"true" if binding.allow_vector_sink else "false"},'
        if binding.allowed_vector_arities
        or binding.vector_arity_modifier_field_id is not None
        else ""
    )
    allow_destination_sink = (
        "\n              .allow_destination_sink = true,"
        if binding.allow_destination_sink
        else ""
    )
    allow_function_symbol = (
        "\n              .allow_function_symbol = true,"
        if binding.allow_function_symbol
        else ""
    )
    type_tag = (
        f'\n              .type_tag = "{binding.type_tag}",'
        if binding.type_tag is not None
        else ""
    )
    cardinality = (
        f"\n              .minimum_elements = {binding.minimum_elements},"
        f"\n              .maximum_elements = {binding.maximum_elements},"
        if binding.minimum_elements is not None
        else ""
    )
    element_shapes = (
        "\n              .allowed_element_shapes = "
        + " | ".join(
            cpp_value(CppDomain.RESOLVED_OPERAND_SHAPES, shape.value)
            for shape in binding.allowed_element_shapes
        )
        + ","
        if binding.allowed_element_shapes
        else ""
    )
    address_state_spaces = (
        "\n              .allowed_address_state_spaces = "
        f"{address_state_spaces_name},"
        if binding.allowed_address_state_spaces
        else ""
    )
    state_space = (
        "\n              .state_space_modifier_field_id = "
        f'"{binding.state_space_modifier_field_id}",'
        if binding.state_space_modifier_field_id is not None
        else ""
    )
    parameter_constraint = ""
    if binding.parameter_constraint is not None:
        availability = dict(
            binding.parameter_constraint.function_availability
        )
        parameter_constraint = f"""
              .parameter_constraint = {{
                  .direction = {cpp_value(CppDomain.PARAMETER_DIRECTIONS, binding.parameter_constraint.direction)},
                  .function_availability = {_emit_availability(availability)},
              }},"""
    register_width_policy = cpp_value(
        CppDomain.REGISTER_WIDTH_POLICIES,
        binding.register_width_policy.value,
    )
    return f"""          check_end::ResolvedOperandBindingDescriptor{{
              .target_field_id = "{binding.target_field_id}",
              .type_expression = {_emit_type_expression_descriptor(binding.type_expression)},
              .register_width_policy = {register_width_policy},
              .role = {cpp_value(CppDomain.RESOLVED_OPERAND_ROLES, binding.role.value)},
              .access = {cpp_value(CppDomain.RESOLVED_OPERAND_ACCESS, binding.access.value)},
              .allowed_shapes = {allowed_shapes},{vector_arities}{vector_arity_modifier}{vector_policy}{allow_vector_sink}{allow_destination_sink}{allow_function_symbol}{type_tag}{cardinality}{element_shapes}{address_state_spaces}{state_space}{parameter_constraint}
          }}"""


def _emit_type_expression_descriptor(
    expression: ResolvedOperandTypeExpression,
) -> str:
    """Emit the constexpr C++ representation of one normalized type source."""

    fixed_scalar_type = cpp_default(CppDomain.SCALAR_TYPES)
    modifier_field_id = '""'
    if expression.kind is ResolvedOperandTypeExpressionKind.FIXED_SCALAR:
        assert expression.scalar_type is not None
        fixed_scalar_type = cpp_value(CppDomain.SCALAR_TYPES, expression.scalar_type)
    elif expression.kind is ResolvedOperandTypeExpressionKind.MODIFIER_FIELD:
        assert expression.modifier_field_id is not None
        modifier_field_id = f'"{expression.modifier_field_id}"'

    return f"""check_end::TypeExpressionDescriptor{{
                  .kind = {cpp_value(CppDomain.RESOLVED_OPERAND_TYPE_EXPRESSION_KINDS, expression.kind.value)},
                  .fixed_scalar_type = {fixed_scalar_type},
                  .modifier_field_id = {modifier_field_id},
              }}"""


def _emit_resolved_variant_descriptor(variant: ResolvedVariant) -> str:
    name = to_file_stem(variant.variant_id)
    return f"""          check_end::ResolvedVariantDescriptor{{
              .variant_name = "{variant.cpp_name}",
              .fields = {name}_fields,
              .modifier_bindings = {name}_modifier_bindings,
              .operand_layouts = {name}_operand_layouts,
          }}"""


def _parse_ptx_version(value: object) -> tuple[int, int]:
    text = str(value)
    pieces = text.split(".")
    if len(pieces) != 2 or not all(piece.isdecimal() for piece in pieces):
        raise ValueError(f"invalid PTX availability version {value!r}")
    major, minor = (int(piece) for piece in pieces)
    if not (0 <= major <= 0xFFFF and 0 <= minor <= 0xFFFF):
        raise ValueError(f"PTX availability version is out of range: {value!r}")
    return major, minor


def _validate_unique_cpp_names(instructions: tuple[ResolvedInstruction, ...]) -> None:
    seen: set[str] = set()
    for instruction in instructions:
        if instruction.cpp_name in seen:
            raise ValueError(
                f"multiple resolved instructions map to C++ type "
                f"{instruction.cpp_name!r}"
            )
        seen.add(instruction.cpp_name)
