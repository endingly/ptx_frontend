"""Emit C++ syntax architecture descriptors from ``ir.syntax_ast``."""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

from code_gen.database import CodegenDatabase
from base.utils import file_stem_to_pascal_case, to_file_stem
from ir.syntax_ast import (
    ModifierPresence,
    OperandLayoutKind,
    OperandPresence,
    OperandSyntaxShape,
    ResolvedValueKind,
    SyntaxInstructionDescriptor,
    SyntaxModifierDescriptor,
    SyntaxOperandLayoutDescriptor,
    SyntaxOperandSlotDescriptor,
    SyntaxVariantDescriptor,
    from_InstructionSpec,
)


_CPP_MODIFIER_PRESENCE = {
    ModifierPresence.ABSENT: "check_end::PresenceRequirement::Absent",
    ModifierPresence.OPTIONAL: "check_end::PresenceRequirement::Optional",
    ModifierPresence.REQUIRED: "check_end::PresenceRequirement::Required",
}

_CPP_OPERAND_PRESENCE = {
    OperandPresence.REQUIRED: "check_end::OperandPresence::Required",
    OperandPresence.OPTIONAL: "check_end::OperandPresence::Optional",
}

_CPP_OPERAND_LAYOUT_KIND = {
    OperandLayoutKind.FLAT: "check_end::OperandLayoutKind::Flat",
}

_CPP_OPERAND_SYNTAX_SHAPES = (
    (OperandSyntaxShape.IDENTIFIER_REF, "check_end::OperandSyntaxShape::Identifier"),
    (OperandSyntaxShape.IMMEDIATE, "check_end::OperandSyntaxShape::Immediate"),
    (OperandSyntaxShape.ADDRESS, "check_end::OperandSyntaxShape::Address"),
    (OperandSyntaxShape.VECTOR_MEMBER, "check_end::OperandSyntaxShape::VectorMember"),
    (OperandSyntaxShape.VECTOR_PACK, "check_end::OperandSyntaxShape::VectorPack"),
)

_CPP_RESOLVED_VALUE_KINDS = {
    ResolvedValueKind.BOOL: "check_end::ResolvedValueKind::Bool",
    ResolvedValueKind.SCALAR_TYPE: "check_end::ResolvedValueKind::ScalarType",
    ResolvedValueKind.REGISTER: "check_end::ResolvedValueKind::Register",
    ResolvedValueKind.IMMEDIATE: "check_end::ResolvedValueKind::Immediate",
    ResolvedValueKind.REG_OR_IMM: "check_end::ResolvedValueKind::RegOrImm",
}


def generate_syntax_descriptor_header(
    database: CodegenDatabase,
    *,
    output_path: Path,
) -> None:
    """Generate private C++ definitions for syntax instruction descriptors."""

    implementations: list[str] = []
    generated_types: set[str] = set()

    for instruction in database.instructions:
        descriptor = from_InstructionSpec(instruction)
        cpp_instruction_name = file_stem_to_pascal_case(descriptor.opcode)
        if cpp_instruction_name in generated_types:
            raise ValueError(
                "cannot generate multiple syntax descriptors for C++ "
                f"instruction type {cpp_instruction_name!r}"
            )

        generated_types.add(cpp_instruction_name)
        implementations.append(
            emit_check_end_instruction_descriptor_implementation(descriptor)
        )

    content = f"""\
// Generated by python/scripts/gen_all.py. Do not edit.
// Generated at: {datetime.now(timezone.utc).isoformat()}
#pragma once

#include "ptx_ir/resolved/ptx_resolved_ir.hpp"

namespace ptx_frontend::resolved_ir {{

{"\n\n".join(implementations)}

}}  // namespace ptx_frontend::resolved_ir
"""

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")


def emit_check_end_instruction_descriptor_implementation(
    descriptor: SyntaxInstructionDescriptor,
) -> str:
    """Emit one ``<Opcode>::get_inst_descriptor`` C++ implementation.

    The storage struct owns all ``std::array`` instances.  The final
    descriptor contains only ``std::span`` views into that static storage.
    Resolved operand semantics remain intentionally value-initialized until
    the Resolved IR generator owns them.
    """

    cpp_instruction_name = file_stem_to_pascal_case(descriptor.opcode)
    storage_name = f"{cpp_instruction_name}DescriptorStorage"
    variant_storage = "\n\n".join(
        _emit_variant_storage(variant) for variant in descriptor.variants
    )
    variants = ",\n".join(
        _emit_variant_descriptor(variant, descriptor.opcode)
        for variant in descriptor.variants
    )

    return f"""\
namespace {{

struct {storage_name} {{
{variant_storage}

  inline static constexpr std::array<check_end::VariantDescriptor, {len(descriptor.variants)}>
      variants = {{
{variants}
      }};

  inline static constexpr check_end::InstructionDescriptor descriptor{{
      .Opcode_name = {_cpp_string(descriptor.opcode)},
      .variants = variants,
  }};
}};

}}  // namespace

const check_end::InstructionDescriptor&
{cpp_instruction_name}::get_inst_descriptor() noexcept {{
  return {storage_name}::descriptor;
}}"""


def _emit_variant_storage(
    variant: SyntaxVariantDescriptor,
) -> str:
    name = to_file_stem(variant.variant_id)
    allowed_value_arrays = "\n\n".join(
        _emit_allowed_value_array(name, index, modifier)
        for index, modifier in enumerate(variant.modifiers)
        if modifier.allowed_spellings
    )
    modifiers = _emit_modifier_array(name, variant.modifiers)
    slot_arrays = "\n\n".join(
        _emit_operand_slot_array(name, index, layout)
        for index, layout in enumerate(variant.operand_layouts)
    )
    layouts = _emit_operand_layout_array(name, variant.operand_layouts)

    parts = [
        part
        for part in (allowed_value_arrays, modifiers, slot_arrays, layouts)
        if part
    ]
    return "\n\n".join(parts)


def _emit_allowed_value_array(
    variant_name: str,
    modifier_index: int,
    modifier: SyntaxModifierDescriptor,
) -> str:
    values = ", ".join(_cpp_string(value) for value in modifier.allowed_spellings)
    return f"""\
  inline static constexpr std::array<std::string_view, {len(modifier.allowed_spellings)}>
      {variant_name}_modifier_{modifier_index}_allowed_values = {{
          {values},
      }};"""


def _emit_modifier_array(
    variant_name: str,
    modifiers: tuple[SyntaxModifierDescriptor, ...],
) -> str:
    entries = ",\n".join(
        _emit_modifier_entry(variant_name, index, modifier)
        for index, modifier in enumerate(modifiers)
    )
    return f"""\
  inline static constexpr std::array<check_end::ModifierDescriptor, {len(modifiers)}>
      {variant_name}_modifiers = {{
{entries}
      }};"""


def _emit_modifier_entry(
    variant_name: str,
    modifier_index: int,
    modifier: SyntaxModifierDescriptor,
) -> str:
    allowed_values = (
        f"{variant_name}_modifier_{modifier_index}_allowed_values"
        if modifier.allowed_spellings
        else "{}"
    )
    return f"""\
          check_end::ModifierDescriptor{{
              .allowed_values = {allowed_values},
              .presence = {_CPP_MODIFIER_PRESENCE[modifier.presence]},
              .kind_id = {_cpp_string(modifier.kind_id)},
              .value_kind = {_CPP_RESOLVED_VALUE_KINDS[modifier.resolved_value_kind]},
          }}"""


def _emit_operand_slot_array(
    variant_name: str,
    layout_index: int,
    layout: SyntaxOperandLayoutDescriptor,
) -> str:
    slots = ",\n".join(
        _emit_operand_slot(slot)
        for slot in layout.slots
    )
    return f"""\
  inline static constexpr std::array<check_end::OperandSlotDescriptor, {len(layout.slots)}>
      {variant_name}_layout_{layout_index}_slots = {{
{slots}
      }};"""


def _emit_operand_layout_array(
    variant_name: str,
    layouts: tuple[SyntaxOperandLayoutDescriptor, ...],
) -> str:
    entries = ",\n".join(
        f"""\
          check_end::OperandLayoutDescriptor{{
              .layout_id = {_CPP_OPERAND_LAYOUT_KIND[layout.kind]},
              .slots = {variant_name}_layout_{index}_slots,
          }}"""
        for index, layout in enumerate(layouts)
    )
    return f"""\
  inline static constexpr std::array<check_end::OperandLayoutDescriptor, {len(layouts)}>
      {variant_name}_operand_layouts = {{
{entries}
      }};"""


def _emit_operand_slot(
    slot: SyntaxOperandSlotDescriptor,
) -> str:
    allowed_shapes = _cpp_operand_syntax_shape(slot.allowed_syntax_shapes)
    return f"""\
          check_end::OperandSlotDescriptor{{
              .field_id = {_cpp_string(slot.field_id)},
              .allowed_shapes = {allowed_shapes},
              .presence = {_CPP_OPERAND_PRESENCE[slot.presence]},
              .value_kind = {_CPP_RESOLVED_VALUE_KINDS[slot.resolved_value_kind]},
              .type_expr = {_cpp_string(slot.type_expr or "")},
          }}"""


def _emit_variant_descriptor(
    variant: SyntaxVariantDescriptor,
    opcode: str,
) -> str:
    name = to_file_stem(variant.variant_id)
    return f"""\
          check_end::VariantDescriptor{{
              .variant_name = {_cpp_string(_cpp_variant_name(opcode, variant.variant_id))},
              .modifiers = {name}_modifiers,
              .operand_layouts = {name}_operand_layouts,
          }}"""


def _cpp_operand_syntax_shape(shape: OperandSyntaxShape) -> str:
    values = [
        cpp_name
        for flag, cpp_name in _CPP_OPERAND_SYNTAX_SHAPES
        if shape & flag
    ]
    if not values:
        raise ValueError("operand syntax shape must not be empty")
    return " | ".join(values)


def _cpp_variant_name(opcode: str, variant_id: str) -> str:
    prefix = f"{opcode}_"
    if not variant_id.startswith(prefix):
        raise ValueError(
            f"variant {variant_id!r} does not start with opcode prefix {prefix!r}"
        )
    return file_stem_to_pascal_case(variant_id.removeprefix(prefix))


def _cpp_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'
