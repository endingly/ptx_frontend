"""Bound large matrix opcode implementations by canonical logical-form ranges."""

from dataclasses import replace
from pathlib import Path

from ptx_frontend.base.utils import generated_at_comment
from ptx_frontend.code_gen.context import GenerationContext
from ptx_frontend.code_gen.matrix_storage import matrix_storage_plan
from ptx_frontend.ir.syntax_ast import from_InstructionSpec

from .category_source import emit_owned_bridge
from .checker_descriptors import _emit_instruction_descriptor_storage as checker_storage
from .resolved_checker import _check_lambda_name, _emit_check_variant_lambda
from .resolved_descriptors import _emit_resolved_descriptor_storage as resolved_storage
from .resolved_resolver import emit_resolve_specialization
from .syntax_descriptors import _emit_instruction_descriptor_storage as syntax_storage


MATRIX_PRIVATE_SHARD_SIZE = 64
# Existing matrix opcodes have at most 552 forms; keep their generated layout.
MATRIX_PRIVATE_SHARD_MIN_VARIANTS = 1024


def matrix_private_shard_count(instruction) -> int:
    """Return bounded private source shards only for exceptionally large opcodes."""

    count = len(instruction.variants)
    if count < MATRIX_PRIVATE_SHARD_MIN_VARIANTS:
        return 0
    return (count + MATRIX_PRIVATE_SHARD_SIZE - 1) // MATRIX_PRIVATE_SHARD_SIZE


def _entry(context: GenerationContext, category: str, opcode: str):
    """Select the one canonical source/resolved binding for an opcode."""

    matches = [
        entry for entry in context.entries
        if entry.specification.codegen_category == category
        and entry.specification.opcode == opcode
    ]
    if len(matches) != 1:
        raise ValueError(f"expected one opcode {opcode!r} in category {category!r}")
    return matches[0]


def _shard_bounds(instruction, shard: int) -> tuple[int, int]:
    """Return the exact half-open canonical-index interval of one shard."""

    count = matrix_private_shard_count(instruction)
    if shard < 0 or shard >= count:
        raise ValueError(f"private matrix shard {shard} is outside {count} shards")
    first = shard * MATRIX_PRIVATE_SHARD_SIZE
    return first, min(first + MATRIX_PRIVATE_SHARD_SIZE, len(instruction.variants))


def _stem(opcode: str, kind: str, shard: int) -> str:
    """Name a private linker symbol without encoding semantic distinctions."""

    return f"{opcode}_{kind}_shard_{shard:03d}"


def generate_matrix_private_descriptor_shard(
    context: GenerationContext, *, category: str, opcode: str,
    kind: str, shard: int, output_path: Path,
) -> None:
    """Emit one static-backed syntax, resolved, or checker descriptor slice."""

    entry = _entry(context, category, opcode)
    instruction = entry.resolved
    first, last = _shard_bounds(instruction, shard)
    if kind == "syntax":
        syntax = from_InstructionSpec(entry.specification)
        storage = syntax_storage(
            replace(syntax, variants=syntax.variants[first:last]),
            context.backend, cpp_name=entry.cpp_name,
        )
        value_type = "check_end::SyntaxVariantDescriptor"
        storage_type = f"{entry.cpp_name}DescriptorStorage"
    elif kind == "resolved":
        storage = resolved_storage(
            replace(instruction, variants=instruction.variants[first:last]),
            context.backend,
        )
        value_type = "check_end::ResolvedVariantDescriptor"
        storage_type = f"{entry.cpp_name}ResolvedDescriptorStorage"
    elif kind == "checker":
        storage = checker_storage(
            replace(instruction, variants=instruction.variants[first:last]),
            context.backend,
        )
        value_type = "checker::VariantDescriptor"
        storage_type = f"{entry.cpp_name}CheckerDescriptorStorage"
    else:
        raise ValueError(f"unknown matrix descriptor shard kind {kind!r}")
    symbol = _stem(opcode, kind, shard)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(f"""\
// Generated by python/scripts/gen_all.py. Do not edit.
{generated_at_comment()}
#include <ptx_frontend/resolved_ir/model/{category}/{opcode}.gen.hpp>

namespace ptx_frontend::resolved_ir::generated_detail {{
namespace {{
{storage}
}}  // namespace

/** Borrow canonical descriptor values whose nested spans have static backing. */
std::span<const {value_type}> {symbol}() noexcept {{
  return {storage_type}::variants;
}}
}}  // namespace ptx_frontend::resolved_ir::generated_detail
""", encoding="utf-8")


def _descriptor_aggregate(opcode: str, kind: str, count: int, shards: int) -> str:
    """Assemble static shard views on first getter use, in canonical order."""

    types = {
        "syntax": ("check_end::SyntaxVariantDescriptor", "check_end::SyntaxInstructionDescriptor", "Opcode_name"),
        "resolved": ("check_end::ResolvedVariantDescriptor", "check_end::ResolvedInstructionDescriptor", "opcode_name"),
        "checker": ("checker::VariantDescriptor", "checker::InstructionDescriptor", "opcode_name"),
    }
    value_type, descriptor_type, opcode_field = types[kind]
    calls = "\n".join(
        f"    append({_stem(opcode, kind, shard)}());"
        for shard in range(shards)
    )
    declarations = "\n".join(
        f"std::span<const {value_type}> {_stem(opcode, kind, shard)}() noexcept;"
        for shard in range(shards)
    )
    return f"""\
{declarations}

/** Preserve canonical variant indexes and static nested descriptor backing. */
const {descriptor_type}& {opcode}_{kind}_descriptor() noexcept {{
  static const auto variants = [] {{
    std::array<{value_type}, {count}> result{{}};
    size_t offset = 0;
    const auto append = [&](std::span<const {value_type}> source) {{
      for (const auto& value : source)
        result[offset++] = value;
    }};
{calls}
    return result;
  }}();
  static const {descriptor_type} descriptor{{
      .{opcode_field} = "{opcode}", .variants = variants}};
  return descriptor;
}}"""


def generate_matrix_private_main(
    context: GenerationContext, *, category: str, opcode: str,
    output_path: Path,
) -> None:
    """Emit only the public getters, resolver, checker dispatch, and owner bridge."""

    entry = _entry(context, category, opcode)
    instruction = entry.resolved
    shards = matrix_private_shard_count(instruction)
    if not shards:
        raise ValueError(f"matrix opcode {opcode!r} does not need private shards")
    cpp_name = entry.cpp_name
    descriptor_assembly = "\n\n".join(
        _descriptor_aggregate(opcode, kind, len(instruction.variants), shards)
        for kind in ("syntax", "resolved", "checker")
    )
    checker_declarations = "\n".join(
        f"CheckResult check_{opcode}_shard_{shard:03d}("
        f"const {cpp_name}&, const Context&, size_t);"
        for shard in range(shards)
    )
    checker_cases = "\n".join(
        f"    case {shard}: variant_check = check_{opcode}_shard_{shard:03d}"
        "(instruction, context, *selected_form); break;"
        for shard in range(shards)
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(f"""\
// Generated by python/scripts/gen_all.py. Do not edit.
{generated_at_comment()}
#include <ptx_frontend/resolved_ir/model/{category}/{opcode}.gen.hpp>
#include <ptx_frontend/resolved_ir/ptx_resolved_ir_resolution_detail.hpp>
#include <ptx_frontend/resolved_ir/ptx_resolved_ir_checker_support.hpp>
#include <ptx_frontend/resolved_ir/ptx_owned_instruction.hpp>
#include "ptx_module_matrix_references.hpp"
#include <array>
#include <span>
#include <typeinfo>
#include <utility>

namespace ptx_frontend::resolved_ir {{
namespace generated_detail {{
{descriptor_assembly}
}}  // namespace generated_detail

const check_end::SyntaxInstructionDescriptor&
{cpp_name}::get_syntax_descriptor() noexcept {{
  return generated_detail::{opcode}_syntax_descriptor();
}}
const check_end::ResolvedInstructionDescriptor&
{cpp_name}::get_resolved_descriptor() noexcept {{
  return generated_detail::{opcode}_resolved_descriptor();
}}
const checker::InstructionDescriptor&
{cpp_name}::get_checker_descriptor() noexcept {{
  return generated_detail::{opcode}_checker_descriptor();
}}

std::optional<size_t> {cpp_name}::matrix_logical_index() const noexcept {{
  const size_t index = static_cast<size_t>(semantic_form.value);
  if (index >= storage_index_by_form.size() ||
      variant.index() != storage_index_by_form[index])
    return std::nullopt;
  return index;
}}
const MatrixInstructionDescriptor*
{cpp_name}::matrix_descriptor() const noexcept {{
  const auto index = matrix_logical_index();
  if (!index)
    return nullptr;
  const auto& selected = get_resolved_descriptor().variants[*index].matrix;
  return selected ? &*selected : nullptr;
}}

{emit_resolve_specialization(instruction, context.backend)}

namespace checker {{
{checker_declarations}

template <>
CheckResult check<{cpp_name}>(const {cpp_name}& instruction,
                              const Context& context) {{
  const auto selected_form = instruction.matrix_logical_index();
  if (!selected_form) {{
    return std::unexpected(CheckDiagnostics{{CheckDiagnostic{{
        .kind = CheckDiagnosticKind::RuleViolation,
        .range = instruction.semantic_form.locs.empty()
            ? context.instruction_range : instruction.semantic_form.locs.front(),
        .message = "Owned matrix logical form does not match its storage.",
    }}}});
  }}
  CheckResult variant_check{{}};
  switch (*selected_form / {MATRIX_PRIVATE_SHARD_SIZE}) {{
{checker_cases}
    default: throw std::bad_variant_access{{}};
  }}
  const auto execution_predicate_check =
      check_execution_predicate(instruction.execution_predicate, context);
  if (execution_predicate_check && variant_check)
    return {{}};
  CheckDiagnostics diagnostics;
  if (!execution_predicate_check) {{
    diagnostics.insert(diagnostics.end(), execution_predicate_check.error().begin(),
                       execution_predicate_check.error().end());
  }}
  if (!variant_check) {{
    diagnostics.insert(diagnostics.end(), variant_check.error().begin(),
                       variant_check.error().end());
  }}
  return std::unexpected(std::move(diagnostics));
}}
}}  // namespace checker

{emit_owned_bridge(cpp_name, opcode, category)}
}}  // namespace ptx_frontend::resolved_ir
""", encoding="utf-8")


def generate_matrix_private_checker_shard(
    context: GenerationContext, *, category: str, opcode: str,
    shard: int, output_path: Path,
) -> None:
    """Emit one independent checker function for at most 64 logical forms."""

    entry = _entry(context, category, opcode)
    instruction = entry.resolved
    first, last = _shard_bounds(instruction, shard)
    storage = matrix_storage_plan(instruction, context.backend)
    if storage is None:
        raise ValueError("sharded matrix checker requires a storage plan")
    lambdas = "\n\n".join(
        _emit_check_variant_lambda(
            instruction, index, instruction.variants[index], context.backend
        )
        for index in range(first, last)
    )
    cases = "\n".join(
        f"    case {index}: return {_check_lambda_name(instruction, instruction.variants[index])}("
        f"std::get<{storage.storage_indexes[index]}>(instruction.variant));"
        for index in range(first, last)
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(f"""\
// Generated by python/scripts/gen_all.py. Do not edit.
{generated_at_comment()}
#include <ptx_frontend/resolved_ir/model/{category}/{opcode}.gen.hpp>
#include <ptx_frontend/resolved_ir/ptx_resolved_ir_checker_support.hpp>
#include <ptx_frontend/resolved_ir/ptx_resolved_ir_resolution_detail.hpp>
#include <utility>

namespace ptx_frontend::resolved_ir::checker {{
/** Check exactly one canonical form in this bounded source interval. */
CheckResult check_{opcode}_shard_{shard:03d}(
    const {entry.cpp_name}& instruction, const Context& context,
    size_t logical_index) {{
{lambdas}
  switch (logical_index) {{
{cases}
    default: throw std::bad_variant_access{{}};
  }}
}}
}}  // namespace ptx_frontend::resolved_ir::checker
""", encoding="utf-8")
