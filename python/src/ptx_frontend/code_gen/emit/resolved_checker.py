from __future__ import annotations


from pathlib import Path

from ptx_frontend.base.utils import generated_at_comment
from ptx_frontend.code_gen.context import GenerationContext
from ptx_frontend.ir.resolved_ir import ResolvedField, ResolvedFieldOrigin, ResolvedInstruction, ResolvedOperandLayout, ResolvedVariant
from ptx_frontend.spec.model import CodegenUnit, SemanticRule
from .operand_views import emit_check_modifier_view, emit_check_modifier_value_view, emit_check_operand_view

def generate_resolved_ir_checker_category_declarations_header(
    context: GenerationContext, *, category: str, output_path: Path
) -> None:
    """Generate one public checker specialization declaration category."""


    instructions = tuple(
        entry.resolved
        for entry in context.entries
        if entry.specification.codegen_category == category
    )
    if not instructions:
        raise ValueError(f"instruction category {category!r} is empty")
    declarations = "\n\n".join(
        emit_check_specialization_declaration(instruction)
        for instruction in instructions
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        f"""\\
// Generated by python/scripts/gen_all.py. Do not edit.
{generated_at_comment()}
#pragma once

#include <ptx_frontend/resolved_ir/ptx_resolved_ir_checker_support.hpp>
#include <ptx_frontend/resolved_ir/model/{category}.gen.hpp>

namespace ptx_frontend::resolved_ir::checker {{

{declarations}

}}  // namespace ptx_frontend::resolved_ir::checker
""",
        encoding="utf-8",
    )


def generate_resolved_ir_checker_declarations_header(
    context: GenerationContext,
    *,
    output_path: Path,
) -> None:
    """Generate the aggregate checker declaration compatibility header."""

    category_headers = tuple(sorted({
        entry.specification.codegen_category for entry in context.entries
    }))

    includes = "\n".join(
        f'#include <ptx_frontend/resolved_ir/checker/{category}.gen.hpp>'
        for category in category_headers
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        f"""\\
// Generated by python/scripts/gen_all.py. Do not edit.
{generated_at_comment()}
#pragma once

{includes}
""",
        encoding="utf-8",
    )


def emit_check_specialization_declaration(
    instruction: ResolvedInstruction,
) -> str:
    return f"""\
template <>
CheckResult check<{instruction.cpp_name}>(
    const {instruction.cpp_name}& instruction, const Context& context);"""


def emit_check_specialization(instruction: ResolvedInstruction, backend: CodegenUnit) -> str:
    variant_lambdas = "\n\n".join(
        _emit_check_variant_lambda(instruction, index, variant, backend)
        for index, variant in enumerate(instruction.variants)
    )
    visitor_lambdas = ", ".join(
        _check_lambda_name(instruction, variant) for variant in instruction.variants
    )
    return f"""\
template <>
CheckResult check<{instruction.cpp_name}>(
    const {instruction.cpp_name}& instruction, const Context& context) {{
  const auto execution_predicate_check = check_execution_predicate(
      instruction.execution_predicate, context);
{variant_lambdas}

  const auto variant_check =
      std::visit(detail::Overloaded{{{visitor_lambdas}}}, instruction.variant);
  if (execution_predicate_check && variant_check)
    return {{}};
  CheckDiagnostics diagnostics;
  if (!execution_predicate_check) {{
    diagnostics.insert(diagnostics.end(), execution_predicate_check.error().begin(),
                       execution_predicate_check.error().end());
  }}
  if (!variant_check) {{
    diagnostics.insert(diagnostics.end(), variant_check.error().begin(),
                       variant_check.error().end());
  }}
  return std::unexpected(std::move(diagnostics));
}}"""


def _emit_check_variant_lambda(
    instruction: ResolvedInstruction,
    variant_index: int,
    variant: ResolvedVariant,
    backend: CodegenUnit,
) -> str:
    modifier_fields = [
        field
        for field in variant.modifier_fields
        if field.origin is ResolvedFieldOrigin.MODIFIER
    ]
    modifier_views = ",\n".join(
        emit_check_modifier_view(instruction, variant, field, backend)
        for field in modifier_fields
    )
    modifier_value_views = ",\n".join(
        emit_check_modifier_value_view(instruction, variant, field, backend, slot_index)
        for slot_index, field in enumerate(modifier_fields)
    )
    operand_check = _emit_check_operand_dispatch(instruction, variant, variant_index, backend)
    lambda_name = _check_lambda_name(instruction, variant)
    return f"""  const auto {lambda_name} =
      [&](const {instruction.cpp_name}::{variant.cpp_name}& selected) -> CheckResult {{
          const std::array<FieldView, {len(modifier_fields)}> fields = {{{{
{modifier_views}
          }}}};
          const std::array<ModifierValueView, {len(modifier_fields)}> modifier_values = {{{{
{modifier_value_views}
          }}}};
          CheckDiagnostics diagnostics;
          const auto common = check_common(
              {instruction.cpp_name}::get_checker_descriptor(), "{variant.cpp_name}",
              context);
          if (!common) {{
            diagnostics.insert(diagnostics.end(), common.error().begin(),
                               common.error().end());
          }}
          const auto modifier_domain = check_modifier_value_domain(
              {instruction.cpp_name}::get_checker_descriptor().variants[{variant_index}]
                  .modifier_value_domains,
              modifier_values, context);
          if (!modifier_domain) {{
            diagnostics.insert(diagnostics.end(), modifier_domain.error().begin(),
                               modifier_domain.error().end());
          }}
          const auto modifier_availability = check_modifier_value_availability(
              {instruction.cpp_name}::get_checker_descriptor().variants[{variant_index}]
                  .modifier_value_availabilities,
              modifier_values, context);
          if (!modifier_availability) {{
            diagnostics.insert(diagnostics.end(),
                               modifier_availability.error().begin(),
                               modifier_availability.error().end());
          }}
{operand_check}
          if (diagnostics.empty())
            return CheckResult{{}};
          return std::unexpected(std::move(diagnostics));
      }};
  static_assert(detail::VariantCheckFunction<
      decltype({lambda_name}), {instruction.cpp_name}::{variant.cpp_name}>);"""


def _emit_check_operand_dispatch(
    instruction: ResolvedInstruction,
    variant: ResolvedVariant,
    variant_index: int,
    backend: CodegenUnit,
) -> str:
    layouts_expr = (
        f"{instruction.cpp_name}::get_resolved_descriptor().variants[{variant_index}]"
        ".operand_layouts"
    )
    checker_variant_expr = (
        f"{instruction.cpp_name}::get_checker_descriptor().variants[{variant_index}]"
    )
    cross_rule_checks = _emit_cross_rule_checks(variant, checker_variant_expr)
    if len(variant.operand_layouts) == 1:
        operand_views = ",\n".join(
            emit_check_operand_view(field, "selected", backend)
            for field in variant.operand_layouts[0].fields
        )
        return f"""          const std::array<OperandView, {len(variant.operand_layouts[0].fields)}> operands = {{{{
{operand_views}
          }}}};
          const auto& layouts = {layouts_expr};
          const auto layout_check = check_operand_layout_tag(
              "{variant.cpp_name}", selected.operand_layout.value, layouts.size(),
              context);
          if (!layout_check) {{
            diagnostics.insert(diagnostics.end(), layout_check.error().begin(),
                               layout_check.error().end());
          }} else {{
            const auto availability_check = check_operand_layout_availability(
                {checker_variant_expr}, selected.operand_layout.value, context);
            if (!availability_check) {{
              diagnostics.insert(diagnostics.end(), availability_check.error().begin(),
                                 availability_check.error().end());
            }}
            const auto layout_modifier_check = check_operand_layout_modifiers(
                {checker_variant_expr}, selected.operand_layout.value,
                modifier_values, context);
            if (!layout_modifier_check) {{
              diagnostics.insert(diagnostics.end(),
                                 layout_modifier_check.error().begin(),
                                 layout_modifier_check.error().end());
            }}
            const auto operand_check = check_operands(
                layouts[selected.operand_layout.value].bindings, fields, operands,
                {checker_variant_expr}.operand_type_compatibilities, context);
            if (!operand_check) {{
              diagnostics.insert(diagnostics.end(), operand_check.error().begin(),
                                 operand_check.error().end());
            }}
{cross_rule_checks}          }}"""

    layout_lambdas = "\n\n".join(
        _emit_check_multi_layout_lambda(
            instruction, variant, variant_index, layout_index, backend
        )
        for layout_index, _ in enumerate(variant.operand_layouts)
    )
    visitor_lambdas = ", ".join(
        _check_layout_lambda_name(variant, layout) for layout in variant.operand_layouts
    )
    return f"""{layout_lambdas}

          const auto& layouts = {layouts_expr};
          const auto layout_check = check_operand_layout_tag(
              "{variant.cpp_name}", selected.operand_layout.value, layouts.size(),
              context);
          if (!layout_check) {{
            diagnostics.insert(diagnostics.end(), layout_check.error().begin(),
                               layout_check.error().end());
          }} else {{
            const auto availability_check = check_operand_layout_availability(
                {checker_variant_expr}, selected.operand_layout.value, context);
            if (!availability_check) {{
              diagnostics.insert(diagnostics.end(), availability_check.error().begin(),
                                 availability_check.error().end());
            }}
            const auto layout_modifier_check = check_operand_layout_modifiers(
                {checker_variant_expr}, selected.operand_layout.value,
                modifier_values, context);
            if (!layout_modifier_check) {{
              diagnostics.insert(diagnostics.end(),
                                 layout_modifier_check.error().begin(),
                                 layout_modifier_check.error().end());
            }}
            const auto payload_check = std::visit(
                detail::Overloaded{{{visitor_lambdas}}}, selected.operands);
            if (!payload_check) {{
              diagnostics.insert(diagnostics.end(), payload_check.error().begin(),
                                 payload_check.error().end());
            }}
          }}"""


def _emit_check_multi_layout_lambda(
    instruction: ResolvedInstruction,
    variant: ResolvedVariant,
    variant_index: int,
    layout_index: int,
    backend: CodegenUnit,
) -> str:
    layout = variant.operand_layouts[layout_index]
    lambda_name = _check_layout_lambda_name(variant, layout)
    operand_views = ",\n".join(
        emit_check_operand_view(field, "payload", backend) for field in layout.fields
    )
    cross_rule_return = f"""
            return check_operands(
                {instruction.cpp_name}::get_resolved_descriptor().variants[{variant_index}]
                    .operand_layouts[{layout_index}]
                    .bindings,
                fields, operands,
                {instruction.cpp_name}::get_checker_descriptor().variants[{variant_index}]
                    .operand_type_compatibilities,
                context);"""
    cross_rule_checks = _emit_cross_rule_checks(
        variant,
        f"{instruction.cpp_name}::get_checker_descriptor().variants[{variant_index}]",
    )
    if cross_rule_checks:
        cross_rule_return = f"""
            const auto operand_check = check_operands(
                {instruction.cpp_name}::get_resolved_descriptor().variants[{variant_index}]
                    .operand_layouts[{layout_index}]
                    .bindings,
                fields, operands,
                {instruction.cpp_name}::get_checker_descriptor().variants[{variant_index}]
                    .operand_type_compatibilities,
                context);
            CheckDiagnostics diagnostics;
            if (!operand_check) {{
              diagnostics.insert(diagnostics.end(), operand_check.error().begin(),
                                 operand_check.error().end());
            }}
{cross_rule_checks}            if (diagnostics.empty())
              return CheckResult{{}};
            return std::unexpected(std::move(diagnostics));"""
    return f"""          const auto {lambda_name} =
              [&](const {instruction.cpp_name}::{variant.cpp_name}::{layout.cpp_name}Operands& payload)
                  -> CheckResult {{
            if (selected.operand_layout.value != {layout_index}) {{
              return std::unexpected(CheckDiagnostics{{CheckDiagnostic{{
                  .kind = CheckDiagnosticKind::OperandLayoutPayloadMismatch,
                  .range = context.instruction_range,
                  .message = "Resolved operand-layout tag and payload alternative disagree.",
              }}}});
            }}
            const std::array<OperandView, {len(layout.fields)}> operands = {{{{
{operand_views}
            }}}};{cross_rule_return}
          }};
          static_assert(detail::VariantCheckFunction<
              decltype({lambda_name}),
              {instruction.cpp_name}::{variant.cpp_name}::{layout.cpp_name}Operands>);"""


def _emit_cross_rule_checks(
    variant: ResolvedVariant,
    checker_variant_expr: str,
) -> str:
    """Emit a variant's cross-rule checks in a fixed order."""

    checks = ""
    checks += f"""            const auto unified_address_check = check_unified_address_suffix(
                {checker_variant_expr}, fields, operands, context);
            if (!unified_address_check) {{
              diagnostics.insert(diagnostics.end(), unified_address_check.error().begin(),
                                 unified_address_check.error().end());
            }}
"""
    if variant.memory_consistency is not None:
        checks += f"""            const auto consistency_check = check_memory_consistency(
                {checker_variant_expr}.memory_consistency, fields, operands, context);
            if (!consistency_check) {{
              diagnostics.insert(diagnostics.end(), consistency_check.error().begin(),
                                 consistency_check.error().end());
            }}
"""
    if variant.memory_vector is not None:
        checks += f"""            const auto memory_vector_check = check_memory_vector(
                {checker_variant_expr}.memory_vector, fields, operands, context);
            if (!memory_vector_check) {{
              diagnostics.insert(diagnostics.end(), memory_vector_check.error().begin(),
                                 memory_vector_check.error().end());
            }}
"""
    if variant.address_alignments:
        checks += f"""            for (const auto& alignment : {checker_variant_expr}.address_alignments) {{
              const auto alignment_check = check_address_alignment(
                  alignment, fields, operands, context);
              if (!alignment_check) {{
                diagnostics.insert(diagnostics.end(), alignment_check.error().begin(),
                                   alignment_check.error().end());
              }}
            }}
"""
    if variant.immediate_value is not None:
        checks += f"""            const auto immediate_value_check = check_immediate_value(
                {checker_variant_expr}.immediate_value, operands, context);
            if (!immediate_value_check) {{
              diagnostics.insert(diagnostics.end(), immediate_value_check.error().begin(),
                                 immediate_value_check.error().end());
            }}
"""
    if variant.immediate_ranges:
        checks += f"""            for (const auto& immediate_range : {checker_variant_expr}.immediate_ranges) {{
              const auto immediate_range_check = check_immediate_range(
                  immediate_range, operands, context);
              if (!immediate_range_check) {{
                diagnostics.insert(diagnostics.end(), immediate_range_check.error().begin(),
                                   immediate_range_check.error().end());
              }}
            }}
"""
    if variant.immediate_multiple_of is not None:
        checks += f"""            const auto immediate_multiple_of_check = check_immediate_multiple_of(
                {checker_variant_expr}.immediate_multiple_of, operands, context);
            if (!immediate_multiple_of_check) {{
              diagnostics.insert(diagnostics.end(), immediate_multiple_of_check.error().begin(),
                                 immediate_multiple_of_check.error().end());
            }}
"""
    if variant.rule is SemanticRule.DATA_MOVEMENT_CVT:
        checks += """            const auto cvt_rule_check = check_cvt_rule(
                modifier_values, operands, context);
            if (!cvt_rule_check) {
              diagnostics.insert(diagnostics.end(), cvt_rule_check.error().begin(),
                                 cvt_rule_check.error().end());
            }
"""
    return checks


def _check_layout_lambda_name(
    variant: ResolvedVariant, layout: ResolvedOperandLayout
) -> str:
    return f"check_{variant.variant_id}_{layout.layout_id}_operands"


def _check_lambda_name(
    instruction: ResolvedInstruction, variant: ResolvedVariant
) -> str:
    variant_suffix = variant.variant_id.removeprefix(f"{instruction.opcode}_")
    return f"check_{variant_suffix}"
