"""Emit opcode-to-resolver dispatch."""

from __future__ import annotations


from pathlib import Path

from ptx_frontend.base.utils import generated_at_comment
from ptx_frontend.code_gen.context import GenerationContext
def generate_resolved_dispatch_source(
    context: GenerationContext,
    *,
    output_path: Path,
) -> None:
    """Generate opcode-independent instruction resolution dispatch."""


    instructions = context.instructions
    branches = "\n\n".join(
        f'  if (ast.opcode.syntax.text == "{instruction.opcode}")\n'
        f'    return resolve_owned_{instruction.cpp_name}(ast, context);'
        for instruction in instructions
    )
    owned_declarations = "\n".join(
        f'/** Resolve and box one {instruction.opcode} instruction. */\n'
        f'std::expected<OwnedInstruction, ResolveDiagnostic> '
        f'resolve_owned_{instruction.cpp_name}('
        'const syntax_ast::AstInstruction&, const ResolveContext*);'
        for instruction in instructions
    )
    content = f"""\
// Generated by python/scripts/gen_all.py. Do not edit.
{generated_at_comment()}

#include <ptx_frontend/resolved_ir/ptx_owned_instruction.hpp>
#include <ptx_frontend/resolved_ir/ptx_resolved_ir_resolution_support.hpp>

#include <utility>

namespace ptx_frontend::resolved_ir {{

{owned_declarations}

namespace {{

std::expected<OwnedInstruction, ResolveDiagnostic>
resolve_instruction(const syntax_ast::AstInstruction& ast,
                    const ResolveContext* context) {{
{branches}

  return std::unexpected(ResolveDiagnostic{{
      .range = ast.opcode.syntax.range,
      .message = "Unknown PTX opcode '" + ast.opcode.syntax.text + "'.",
  }});
}}

}}  // namespace

std::expected<OwnedInstruction, ResolveDiagnostic>
resolveInstruction(const syntax_ast::AstInstruction& ast) {{
  return resolve_instruction(ast, nullptr);
}}

std::expected<OwnedInstruction, ResolveDiagnostic>
resolveInstruction(const syntax_ast::AstInstruction& ast,
                   const ResolveContext& context) {{
  return resolve_instruction(ast, &context);
}}

}}  // namespace ptx_frontend::resolved_ir
"""

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")
