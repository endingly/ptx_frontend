"""Emit the global direct-class identity and resolver dispatch."""

from __future__ import annotations

from pathlib import Path

from ptx_frontend.code_gen.context import GenerationContext
from ptx_frontend.code_gen.emit.resolved_model import INCLUDE_ROOT


def generate_resolved_dispatch_source(
    context: GenerationContext, *, output_path: Path
) -> None:
    """Emit prefix decoding and opcode syntax dispatch without all form headers."""

    declarations = "\n".join(
        f"/** Resolve the selected {entry.specification.opcode} source form. */\n"
        f"std::expected<std::unique_ptr<Instruction>, ResolveDiagnostic> "
        f"resolve{entry.cpp_name}(const syntax_ast::AstInstruction&, "
        "const ResolveContext*);"
        for entry in context.entries
    )
    name_cases = "\n".join(
        f'    case Opcode::{entry.cpp_name}: return "{entry.specification.opcode}";'
        for entry in context.entries
    )
    dispatch = "\n".join(
        f'  if (ast.opcode.syntax.text == "{entry.specification.opcode}")\n'
        f'    return resolve{entry.cpp_name}(ast, context);'
        for entry in context.entries
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(f"""// Generated by ptx_frontend resolved IR code generation. Do not edit.
#include <{INCLUDE_ROOT}/ptx_instruction_catalogue.gen.hpp>
#include <ptx_frontend/syntax/ptx_syntax_ast.hpp>
#include <utility>

namespace ptx_frontend::resolved_ir {{

{declarations}

/** Destroy an exact concrete instruction through the base interface. */
Instruction::~Instruction() = default;

/** Decode the full-context category/opcode prefix from an exact form identity. */
Opcode Instruction::opcode_kind() const noexcept {{
  return static_cast<Opcode>(
      static_cast<std::uint32_t>(instruction_kind()) & 0xffff0000u);
}}

/** Map an opcode family to its canonical mnemonic. */
std::string_view Instruction::opcode_name() const noexcept {{
  switch (opcode_kind()) {{
{name_cases}
  }}
  std::unreachable();
}}

namespace {{
/** Resolve one syntax opcode using the optional bound declaration context. */
std::expected<std::unique_ptr<Instruction>, ResolveDiagnostic> resolve_instruction(
    const syntax_ast::AstInstruction& ast, const ResolveContext* context) {{
{dispatch}
  return std::unexpected(ResolveDiagnostic{{
      .range = ast.opcode.syntax.range,
      .message = "Unknown PTX opcode '" + ast.opcode.syntax.text + "'.",
  }});
}}
}}  // namespace

/** Resolve an unbound instruction to an exact final class. */
std::expected<std::unique_ptr<Instruction>, ResolveDiagnostic> resolveInstruction(
    const syntax_ast::AstInstruction& ast) {{
  return resolve_instruction(ast, nullptr);
}}

/** Resolve a bound instruction to an exact final class. */
std::expected<std::unique_ptr<Instruction>, ResolveDiagnostic> resolveInstruction(
    const syntax_ast::AstInstruction& ast, const ResolveContext& context) {{
  return resolve_instruction(ast, &context);
}}

}}  // namespace ptx_frontend::resolved_ir
""", encoding="utf-8")
