def _enum(name: str, members: tuple[str, ...]) -> str:
    """Emit a small closed public enum with stable catalogue order."""

    return (f"/** {name} identity for fixed TCGEN descriptor queries. */\n"
            f"enum class {name} : uint8_t {{ " + ", ".join(members) + " };\n")


