def generate_tcgen_descriptor_source(
    _context: GenerationContext, *, output_path: Path
) -> None:
    """Write pure defined-field algorithms and catalogue-derived static rows."""

    content = _source_text()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")


def _source_text() -> str:
    """Substitute all encoded facts from the immutable Python catalogue."""

    content = _SOURCE
    for word in domain.WORDS:
        rows = ",\n".join(
            '  TcgenBitField{"%s", %d, %d, %s}' % (
                field.name, field.first, field.width,
                ("std::nullopt" if field.fixed is None
                 else f"std::optional<uint32_t>{{{field.fixed}}}"),
            ) for field in word.fields
        )
        content = content.replace(f"__FIELDS_{word.name.upper()}__", rows)
        content = content.replace(f"__COUNT_{word.name.upper()}__", str(len(word.fields)))
        content = content.replace(f"__UNCLASSIFIED_{word.name.upper()}__",
                                  str(word.unclassified) + "ULL")
        content = content.replace(f"__FIXED_{word.name.upper()}__",
                                  str(word.fixed_mask) + "ULL")
        content = content.replace(f"__RESERVED_{word.name.upper()}__",
                                  str(word.reserved_mask) + "ULL")
        for field in word.fields:
            key = f"__{word.name.upper()}_{field.name.upper()}__"
            content = content.replace(key, str(field.first))
    content = content.replace("__SWIZZLE_ROWS__", ", ".join(
        f"{{{code}, TcgenSwizzle::{name}}}" for code, name in domain.SWIZZLES))
    content = content.replace("__SWIZZLE_COUNT__", str(len(domain.SWIZZLES)))
    backing, rows = _kind_rows()
    content = content.replace("__KIND_BACKING__", backing)
    content = content.replace("__KIND_ROWS__", rows)
    content = content.replace("__KIND_COUNT__", str(len(domain.KINDS)))
    content = content.replace("__LAYOUT_ROWS__", _layout_rows())
    content = content.replace("__PATTERN_ROWS__", ", ".join(
        f"{{{code}, {bytes_}}}" for code, bytes_ in domain.ORDINARY_PATTERN_BYTES))
    content = content.replace("__ABS_TARGET__", domain.ABSOLUTE_TARGET[0])
    content = content.replace("__ABS_PTX_MAJOR__", str(domain.ABSOLUTE_TARGET[1]))
    content = content.replace("__ABS_PTX_MINOR__", str(domain.ABSOLUTE_TARGET[2]))
    content = content.replace("__SPECIAL_ATOM_M__", str(domain.SPECIAL_ATOM[2]))
    content = content.replace("__SPECIAL_ATOM_N__", str(domain.SPECIAL_ATOM[3]))
    content = content.replace("__PARTITION_ROWS__", ", ".join(
        f"{{{m}, {count}}}" for m, count in domain.ZERO_PARTITIONS))
    return content


def _kind_rows() -> tuple[str, str]:
    """Emit one immutable record per explicit instruction kind."""

    backing: list[str] = []
    lines: list[str] = []
    for kind in domain.KINDS:
        table = next(i for i, word in enumerate(domain.WORDS)
                     if word.name == kind.table)
        stem = kind.name
        for suffix, cpp_type, rows, render in (
            ("A", "TypeCode", kind.a_types,
             lambda code, name: f"{{{code}, MatrixElementType::{name}}}"),
            ("B", "TypeCode", kind.b_types,
             lambda code, name: f"{{{code}, MatrixElementType::{name}}}"),
            ("D", "TypeCode", kind.d_types,
             lambda code, name: f"{{{code}, MatrixElementType::{name}}}"),
            ("ScaleIds", "uint8_t", tuple((code, "") for code in kind.scale_ids),
             lambda code, _name: str(code)),
            ("ScaleTypes", "ScaleCode", kind.scale_types,
             lambda code, name: f"{{{code}, MatrixScaleType::{name}}}"),
        ):
            values = ", ".join(render(code, name) for code, name in rows)
            backing.append(
                f"constexpr std::array<{cpp_type}, {len(rows)}> k{stem}{suffix} = "
                + "{{" + values + "}};"
            )
        lines.append(
            "  KindRule{TcgenMmaKind::%s, %d, k%sA, k%sB, k%sD, %s, %s, %s, k%sScaleIds, k%sScaleTypes}," % (
                kind.name, table, stem, stem, stem,
                "true" if kind.saturation else "false",
                "true" if kind.negate else "false",
                "true" if kind.transpose else "false", stem, stem,
            )
        )
    return "\n".join(backing), "\n".join(lines)


def _layout_rows() -> str:
    """Emit all eight relative rows with symbolic rather than truncated T."""

    def symbol(name: str) -> str:
        return {"one": "One", "T": "T", "m": "M", "k": "K",
                "LBO": "LBO", "SBO": "SBO"}[name]

    def group(items: tuple[domain.LayoutTerm, ...]) -> str:
        terms = ", ".join(
            f"TcgenLayoutTerm{{{term.coefficient}, TcgenLayoutSymbol::{symbol(term.symbol)}}}"
            for term in items
        )
        return "TcgenLayoutTuple{{" + terms + "}, " + str(len(items)) + "}"

    lines = []
    for row in domain.RELATIVE_LAYOUTS:
        shape = ", ".join(group(item) for item in row.shape)
        stride = ", ".join(group(item) for item in row.stride)
        swizzle = ", ".join(str(item) for item in row.swizzle_tuple)
        lines.append(
            "  TcgenRelativeLayoutRow{TcgenMajor::" + row.major +
            ", TcgenSwizzle::" + row.swizzle + ", {" + shape + "}, {" +
            stride + "}, {" + swizzle + "}},"
        )
    return "\n".join(lines)


